/// Shader生成器
pub struct ShaderGenerator {
    options: CodeGenOptions,
}

impl ShaderGenerator {
    pub fn new(options: CodeGenOptions) -> Self {
        Self { options }
    }

    /// 生成顶点着色器
    fn generate_vertex_shader(&self, material: &Material) -> String {
        let mut code = String::new();

        if self.options.add_docs {
            code.push_str("// Vertex shader for material\n");
            code.push_str(&format!("// Material: {}\n", material.name));
        }

        code.push_str("\nstruct VertexInput {\n");
        code.push_str("    @location(0) position: vec3<f32>,\n");
        code.push_str("    @location(1) normal: vec3<f32>,\n");
        code.push_str("    @location(2) uv: vec2<f32>,\n");
        code.push_str("}\n\n");

        code.push_str("struct VertexOutput {\n");
        code.push_str("    @builtin(position) clip_position: vec4<f32>,\n");
        code.push_str("    @location(0) uv: vec2<f32>,\n");
        code.push_str("    @location(1) normal: vec3<f32>,\n");
        code.push_str("}\n\n");

        code.push_str("@vertex\n");
        code.push_str("fn vs_main(input: VertexInput) -> VertexOutput {\n");
        code.push_str("    var output: VertexOutput;\n");
        code.push_str("    output.clip_position = vec4<f32>(input.position, 1.0);\n");
        code.push_str("    output.uv = input.uv;\n");
        code.push_str("    output.normal = input.normal;\n");
        code.push_str("    return output;\n");
        code.push_str("}\n");

        code
    }

    /// 生成片段着色器
    fn generate_fragment_shader(&self, material: &Material) -> String {
        let mut code = String::new();

        if self.options.add_docs {
            code.push_str("// Fragment shader for material\n");
            code.push_str(&format!("// Material: {}\n", material.name));
        }

        code.push_str("\n@group(0) @binding(0)\n");
        code.push_str("var texture_sampler: sampler;\n\n");

        code.push_str("@group(0) @binding(1)\n");
        code.push_str("var base_color_texture: texture_2d<f32>;\n\n");

        code.push_str("struct FragmentInput {\n");
        code.push_str("    @location(0) uv: vec2<f32>,\n");
        code.push_str("    @location(1) normal: vec3<f32>,\n");
        code.push_str("}\n\n");

        code.push_str("struct FragmentOutput {\n");
        code.push_str("    @location(0) color: vec4<f32>,\n");
        code.push_str("}\n\n");

        code.push_str("@fragment\n");
        code.push_str("fn fs_main(input: FragmentInput) -> FragmentOutput {\n");
        code.push_str("    var output: FragmentOutput;\n");
        code.push_str(
            "    let color = textureSample(base_color_texture, texture_sampler, input.uv);\n",
        );
        code.push_str("    output.color = color;\n");
        code.push_str("    return output;\n");
        code.push_str("}\n");

        code
    }
}

impl CodeGenerator<Material> for ShaderGenerator {
    fn generate(&self, material: &Material) -> Result<GeneratedCode, CodeGenError> {
        self.validate(material)?;

        let vs_code = self.generate_vertex_shader(material);
        let fs_code = self.generate_fragment_shader(material);

        let full_code = format!("// Vertex Shader\n{vs_code}\n\n// Fragment Shader\n{fs_code}");

        let file_name = format!(
            "{}_shader.wgsl",
            self.sanitize_name(&material.name).to_lowercase()
        );

        Ok(GeneratedCode {
            code: full_code,
            file_path: PathBuf::from(file_name),
            dependencies: vec![],
        })
    }

    fn validate(&self, material: &Material) -> Result<(), CodeGenError> {
        if material.name.is_empty() {
            return Err(CodeGenError::InvalidInput(
                "Material name is empty".to_string(),
            ));
        }
        Ok(())
    }

    fn get_dependencies(&self, _material: &Material) -> Vec<String> {
        vec![]
    }
}

impl ShaderGenerator {
    fn sanitize_name(&self, name: &str) -> String {
        name.chars()
            .map(|c| if c.is_alphanumeric() { c } else { '_' })
            .collect::<String>()
            .trim_matches('_')
            .to_string()
    }
}

