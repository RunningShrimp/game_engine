//! # Code Generator Trait
//!
//! 代码生成器trait - 将编辑器中的资源转换为Rust代码。
//!
//! ## 核心组件
//!
//! 1. **CodeGenerator** - 代码生成器trait
//! 2. **PrefabGenerator** - 场景Prefab代码生成
//! 3. **ShaderGenerator** - 材质Shader代码生成
//! 4. **ParticleGenerator** - 粒子系统代码生成
//! 5. **BehaviorTreeGenerator** - 行为树代码生成
//!
//! ## 使用示例
//!
//! ```rust,no_run
//! use game_engine::editor::code_generator::*;
//!
//! // 创建Prefab生成器
//! let generator = PrefabGenerator::new(CodeGenOptions::default());
//! let scene = Scene::from_file("scene.json").unwrap();
//! let code = generator.generate(&scene).unwrap();
//! std::fs::write(code.file_path, code.code).unwrap();
//! ```

use std::path::PathBuf;
use thiserror::Error;

/// 代码生成错误
#[derive(Debug, Error)]
pub enum CodeGenError {
    #[error("IO error: {0}")]
    Io(#[from] std::io::Error),

    #[error("Template error: {0}")]
    Template(String),

    #[error("Invalid input: {0}")]
    InvalidInput(String),

    #[error("Generation failed: {0}")]
    GenerationFailed(String),
}

// ==================== 占位类型定义 ====================
// 注意：这些是简化的类型定义，用于框架展示
// 实际实现时应该使用项目中的真实类型

/// 场景占位类型
#[derive(Clone, Debug)]
pub struct Scene {
    pub name: String,
    pub entities: Vec<Entity>,
}

/// 实体占位类型
#[derive(Clone, Debug)]
pub struct Entity {
    pub name: String,
    pub components: Vec<ComponentData>,
}

/// 组件数据占位类型
#[derive(Clone, Debug)]
pub struct ComponentData(String);

/// 材质占位类型
#[derive(Clone, Debug)]
pub struct Material {
    pub name: String,
    pub shader_type: ShaderType,
}

/// 着色器类型
#[derive(Clone, Debug)]
pub enum ShaderType {
    Pbr,
    Unlit,
    Custom,
}

/// 粒子系统占位类型
#[derive(Clone, Debug)]
pub struct ParticleSystem {
    pub name: String,
    pub max_particles: usize,
    pub emission_rate: f32,
    pub lifetime: std::time::Duration,
}

/// 行为树占位类型
#[derive(Clone, Debug)]
pub struct BehaviorTree {
    pub name: String,
    pub root_node: Box<BehaviorNode>,
}

/// 行为节点占位类型
#[derive(Clone, Debug)]
pub struct BehaviorNode;

/// 代码生成结果
#[derive(Clone, Debug)]
pub struct GeneratedCode {
    pub code: String,
    pub file_path: PathBuf,
    pub dependencies: Vec<String>,
}

/// 代码生成器trait
pub trait CodeGenerator<T> {
    /// 生成代码
    fn generate(&self, input: &T) -> Result<GeneratedCode, CodeGenError>;

    /// 验证输入
    fn validate(&self, input: &T) -> Result<(), CodeGenError>;

    /// 获取生成的依赖项
    fn get_dependencies(&self, input: &T) -> Vec<String>;
}

/// 代码生成选项
#[derive(Clone, Debug)]
pub struct CodeGenOptions {
    /// 是否添加文档注释
    pub add_docs: bool,
    /// 是否格式化代码
    pub format_code: bool,
    /// 命名空间前缀
    pub namespace: Option<String>,
    /// 是否生成测试
    pub generate_tests: bool,
}

impl Default for CodeGenOptions {
    fn default() -> Self {
        Self {
            add_docs: true,
            format_code: true,
            namespace: None,
            generate_tests: false,
        }
    }
}

// ==================== 场景Prefab生成器 ====================

/// Prefab生成器
pub struct PrefabGenerator {
    options: CodeGenOptions,
}

impl PrefabGenerator {
    pub fn new(options: CodeGenOptions) -> Self {
        Self { options }
    }

    /// 生成struct定义
    fn generate_struct_def(&self, scene: &Scene) -> String {
        let name = self.sanitize_name(&scene.name);
        let mut code = String::new();

        // 文档注释
        if self.options.add_docs {
            code.push_str(&format!("/// Auto-generated Prefab: {}\n", scene.name));
            code.push_str("///\n");
            code.push_str("/// Generated by game_engine editor\n");
            code.push_str(&format!("/// Entity count: {}\n", scene.entities.len()));
            code.push_str("#[derive(Clone, Debug)]\n");
        }

        // struct定义
        code.push_str(&format!("pub struct {name} {{\n"));

        // 添加字段
        for entity in &scene.entities {
            let field_name = self.sanitize_name(&entity.name);
            let field_type = self.get_entity_type(entity);
            code.push_str(&format!("    pub {field_name}: {field_type},\n"));
        }

        code.push_str("}\n\n");

        // 实现Default
        code.push_str(&format!("impl Default for {name} {{\n"));
        code.push_str("    fn default() -> Self {\n");
        code.push_str("        Self {\n");

        for entity in &scene.entities {
            let field_name = self.sanitize_name(&entity.name);
            code.push_str(&format!(
                "            {}: {}::default(),\n",
                field_name,
                self.get_entity_type(entity)
            ));
        }

        code.push_str("        }\n");
        code.push_str("    }\n");
        code.push_str("}\n\n");

        code
    }

    /// 生成创建函数
    fn generate_creation_func(&self, scene: &Scene) -> String {
        let name = self.sanitize_name(&scene.name);
        let mut code = String::new();

        if self.options.add_docs {
            code.push_str("/// Creates the prefab in the given world\n");
        }

        code.push_str(&format!(
            "pub fn create_{}_prefab(world: &mut World) -> Result<Entity, CreateError> {{\n",
            name.to_lowercase()
        ));

        // 创建根实体
        code.push_str("    let root = world.spawn_empty().id();\n\n");

        // 创建子实体
        for entity in &scene.entities {
            code.push_str(&self.generate_entity_creation(entity, "root"));
        }

        code.push_str("\n    Ok(root)\n");
        code.push_str("}\n\n");

        code
    }

    /// 生成实体创建代码
    fn generate_entity_creation(&self, entity: &Entity, parent: &str) -> String {
        let mut code = String::new();
        let entity_name = self.sanitize_name(&entity.name);

        // 创建实体
        code.push_str(&format!(
            "    let {entity_name} = world.spawn_empty().id();\n"
        ));

        // 添加组件
        for component in &entity.components {
            code.push_str(&format!("    world.entity_mut({entity_name})\n"));
            code.push_str(&format!(
                "        .insert({});\n",
                self.generate_component_init(component)
            ));
        }

        // 设置父子关系
        code.push_str(&format!("    world.entity_mut({entity_name})\n"));
        code.push_str(&format!("        .set_parent_in_place({parent});\n\n"));

        code
    }

    /// 生成组件初始化代码
    fn generate_component_init(&self, component: &ComponentData) -> String {
        // 简化版 - 实际实现需要解析组件数据
        "ComponentData { /* data */ }".to_string()
    }

    /// 获取实体类型
    fn get_entity_type(&self, _entity: &Entity) -> String {
        "Entity".to_string()
    }

    /// 清理名称为合法Rust标识符
    fn sanitize_name(&self, name: &str) -> String {
        name.chars()
            .map(|c| if c.is_alphanumeric() { c } else { '_' })
            .collect::<String>()
            .trim_matches('_')
            .to_string()
    }
}

impl CodeGenerator<Scene> for PrefabGenerator {
    fn generate(&self, scene: &Scene) -> Result<GeneratedCode, CodeGenError> {
        self.validate(scene)?;

        let mut code = String::new();

        // 文件头
        code.push_str("// Auto-generated by game_engine editor\n");
        code.push_str("// DO NOT EDIT MANUALLY\n\n");
        code.push_str("use bevy_ecs::world::World;\n");
        code.push_str("use bevy_ecs::entity::Entity;\n\n");

        // 生成struct定义
        code.push_str(&self.generate_struct_def(scene));

        // 生成创建函数
        code.push_str(&self.generate_creation_func(scene));

        // 生成测试（可选）
        if self.options.generate_tests {
            // TODO: 实现测试生成
            code.push_str("\n// Tests will be generated here\n");
        }

        let file_name = format!(
            "{}_prefab.rs",
            self.sanitize_name(&scene.name).to_lowercase()
        );

        Ok(GeneratedCode {
            code,
            file_path: PathBuf::from(file_name),
            dependencies: vec!["bevy_ecs".to_string()],
        })
    }

    fn validate(&self, scene: &Scene) -> Result<(), CodeGenError> {
        if scene.name.is_empty() {
            return Err(CodeGenError::InvalidInput(
                "Scene name is empty".to_string(),
            ));
        }
        if scene.entities.is_empty() {
            return Err(CodeGenError::InvalidInput(
                "Scene has no entities".to_string(),
            ));
        }
        Ok(())
    }

    fn get_dependencies(&self, _scene: &Scene) -> Vec<String> {
        vec!["bevy_ecs".to_string()]
    }
}

