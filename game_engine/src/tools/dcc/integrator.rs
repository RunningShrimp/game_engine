    fn test_script_generator_creation() {
        let generator = ScriptGenerator::new();
        assert!(generator.operations().is_empty());
    }

    #[test]
    fn test_add_operation() {
        let mut generator = ScriptGenerator::new();
        let op = EditorOperation::VertexTransform {
            vertices: vec![0, 1, 2],
            transform: Mat4::IDENTITY,
        };

        generator.add_operation(op);
        assert_eq!(generator.operations().len(), 1);
    }

